import { betterAuth, type BetterAuthOptions, type BetterAuthPlugin } from 'better-auth';
import { APIError, createAuthMiddleware, getOAuthState } from 'better-auth/api';
import { nextCookies } from 'better-auth/next-js';
import { genericOAuth, type GenericOAuthConfig } from 'better-auth/plugins';

type UserFields = NonNullable<NonNullable<BetterAuthOptions['user']>['additionalFields']>;
type OAuthTokens = Parameters<NonNullable<GenericOAuthConfig['getUserInfo']>>[0];

export interface ExchangeCodeContext {
  code: string;
  codeVerifier?: string;
  redirectURI: string;
  /** OIDC nonce generated by Better Auth for this sign-in, if any. */
  nonce?: string;
  /** Aborts the sign-in; `reason` is appended to the login-failed redirect as `?error=<reason>`. */
  fail: (reason: string) => never;
}

export interface CreateAuthOptions<TUserFields extends UserFields> {
  /** Falls back to Better Auth's own env lookup when omitted. */
  secret?: string;
  /** Account provider id under which the tokens are stored. */
  providerId: string;
  sessionLifetimeSeconds: number;
  /** Where Better Auth sends the browser on an unhandled API error. */
  errorURL: string;
  /** Standard OIDC settings (clientId, discoveryUrl, scopes, clientSecret, ...). `pkce` defaults to true. */
  oidc: Omit<GenericOAuthConfig, 'providerId' | 'getToken' | 'getUserInfo' | 'mapProfileToUser'>;
  /** Extra user fields persisted in the session cookie (e.g. `role`). Don't set `input: false`, see `mapProfileToUser`. */
  userFields?: TUserFields;
  /**
   * Replaces the standard code-for-token exchange, e.g. to redeem the code through your own API.
   * Omit it to let Better Auth talk to the provider's token endpoint directly.
   */
  exchangeCode?: (context: ExchangeCodeContext) => Promise<OAuthTokens>;
  /** Replaces the default userinfo / ID-token lookup. Receives whatever `exchangeCode` returned. */
  getUserInfo?: GenericOAuthConfig['getUserInfo'];
  /** Only the fields returned here are copied onto the local user, so custom `userFields` must be mapped. */
  mapProfileToUser?: GenericOAuthConfig['mapProfileToUser'];
  /** Refresh name and other mapped fields on every sign-in. Defaults to true. */
  overrideUserInfo?: boolean;
  /** Additional plugins; they run before `nextCookies()`, which is always appended last. */
  plugins?: BetterAuthPlugin[];
}

export const createAuth = <const TUserFields extends UserFields = Record<never, never>>({
  secret,
  providerId,
  sessionLifetimeSeconds,
  errorURL,
  oidc,
  userFields,
  exchangeCode,
  getUserInfo,
  mapProfileToUser,
  overrideUserInfo = true,
  plugins = [],
}: CreateAuthOptions<TUserFields>) => {
  // Better Auth swallows errors thrown from `getToken` and redirects with `error=invalid_code`;
  // the real reason is parked here (keyed by the one-time code) for the callback after-hook.
  const failures = new Map<string, string>();

  const fail = (code: string, reason: string): never => {
    failures.set(code, reason);

    throw new APIError('UNAUTHORIZED', { message: reason });
  };

  return betterAuth({
    user: {
      additionalFields: userFields ?? ({} as TUserFields),
    },
    // Without `input: false`, clients could write custom user fields through these endpoints.
    disabledPaths: ['/update-user', '/change-email', '/delete-user'],
    account: {
      storeAccountCookie: true,
      storeStateStrategy: 'cookie',
    },
    session: {
      expiresIn: sessionLifetimeSeconds,
      // A sliding session would outlive a fixed-lifetime access token.
      disableSessionRefresh: true,
      // Also sets the lifetime of the session and account cookies (the access token is in the latter).
      cookieCache: {
        enabled: true,
        strategy: 'jwe',
        maxAge: sessionLifetimeSeconds,
        refreshCache: false,
      },
    },
    hooks: {
      after: createAuthMiddleware(async (ctx) => {
        if (ctx.path !== '/callback/:id') {
          return;
        }

        const location = ctx.context.responseHeaders?.get('location');

        if (!location) {
          return;
        }

        const url = new URL(location, ctx.context.baseURL);
        const code: unknown = ctx.query?.code;
        const parked = typeof code === 'string' ? failures.get(code) : undefined;

        if (typeof code === 'string') {
          failures.delete(code);
        }

        if (!parked) {
          return;
        }

        url.searchParams.set('error', parked);

        throw ctx.redirect(url.toString());
      }),
    },
    onAPIError: { errorURL },
    plugins: [
      genericOAuth({
        config: [
          {
            pkce: true,
            ...oidc,
            providerId,
            overrideUserInfo,
            getUserInfo,
            mapProfileToUser,
            getToken: exchangeCode
              ? async ({ code, codeVerifier, redirectURI }) => {
                  const oauthState = await getOAuthState();
                  const nonce = oauthState && 'idTokenNonce' in oauthState ? oauthState.idTokenNonce : undefined;

                  return exchangeCode({
                    code,
                    codeVerifier,
                    redirectURI,
                    nonce,
                    fail: (reason) => fail(code, reason),
                  });
                }
              : undefined,
          },
        ],
      }),
      ...plugins,
      // Must stay last: applies cookies set by `auth.api.*` calls in server actions.
      nextCookies(),
    ],
    secret,
  });
};
